export function getTranslation(lang: LanguageCode, key: string, params?: Record<string, string | number>): string {
  const dict = translations[lang] || translations.en;
  let text = dict[key] || translations.en[key] || key;

  if (params) {
    Object.entries(params).forEach(([paramKey, paramVal]) => {
      text = text.replace(new RegExp(`\\{${paramKey}\\}`, 'g'), String(paramVal));
    });
  }

  return text;
}

export function formatMonthNameWithLang(yearMonth: string, lang: LanguageCode): string {
  const [year, month] = yearMonth.split('-');
  const date = new Date(parseInt(year, 10), parseInt(month, 10) - 1, 1);
  
  const localeMap: Record<LanguageCode, string> = {
    en: 'en-US',
    es: 'es-ES',
    fr: 'fr-FR',
    de: 'de-DE',
    pt: 'pt-BR',
    it: 'it-IT',
    ja: 'ja-JP',
    zh: 'zh-CN',
    id: 'id-ID',
  };

  try {
    return date.toLocaleDateString(localeMap[lang] || 'en-US', {
      month: 'long',
      year: 'numeric',
    });
  } catch {
    return date.toLocaleDateString('en-US', { month: 'long', year: 'numeric' });
  }
}

